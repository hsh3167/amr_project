"""Side-view (Y-Z) underside silhouettes of the Pro model (cad/layout.json, bogie concept) for the 2-D drive simulation.

Same method as cad/p30/side_profile.py (lowest solid-bounding-box Z at each 10 mm Y station over the full width),
split by what the part moves with:
  sprung : chassis, plates, structure, electronics, sensors, the chassis side of the pivots
  bogie  : the parts that turn with the bogie (link, torque plate, U bracket, stoppers ...), tyre and caster excluded
  rear   : the parts that swing with the rear caster hinge arms, caster excluded
Caster groups and the tyres are modelled as circles by the simulation; springs are left out (they join two bodies).
Z values are absolute at the nominal pose (ground Z = 0).
python -m cad.side_profile  ->  cad-output/side_profile.json
"""
import json

from .assembly import build_records
from .p30.side_profile import silhouette, STEP
from .parameters import ROOT, load_design


def build(d=None):
    d = d or load_design()
    records = build_records(d)
    sets = {'sprung': [], 'bogie': [], 'rear': []}
    ymin = ymax = zmax = 0.0
    for r in records:
        if r.group.startswith('caster_') or 'spring_length_mm' in r.metadata:
            continue
        if r.name.startswith(('30_', '31_')):            # tyre and motor casing: the 90 mm wheel circle
            continue
        key = r.metadata.get('moving_wheel')
        target = sets['bogie'] if key in ('LEFT', 'RIGHT') else sets['rear'] if key in ('LB', 'RB') else sets['sprung']
        for s in r.shape.solids():
            bb = s.bounding_box()
            target.append((bb.min.Y, bb.max.Y, bb.min.Z, bb.max.Z))
            if target is sets['sprung']:
                ymin, ymax, zmax = min(ymin, bb.min.Y), max(ymax, bb.max.Y), max(zmax, bb.max.Z)
    sp = sets['sprung']
    nose = min(b[2] for b in sp if b[1] >= ymax-15)
    tail = min(b[2] for b in sp if b[0] <= ymin+15)
    q = d.layout['suspension']
    return {
        'revision': d.layout['revision'],
        'note': 'Generated by python -m cad.side_profile from the build123d records (solid bounding boxes, min Z over the full width, '
                'nominal pose, ground Z = 0). The simulation moves the bogie set with the bogie and the rear set with the rear caster arms.',
        'station_mm': STEP,
        'sprung_bottom': silhouette(sp, round(ymin/STEP)*STEP, round(ymax/STEP)*STEP),
        'bogie_bottom': silhouette(sets['bogie'], -300, 300),
        'rear_bottom': silhouette(sets['rear'], -400, 0),
        'extent_y': [round(ymin, 1), round(ymax, 1)],
        'top_z': round(zmax, 1),
        'nose': {'y': round(ymax, 1), 'z_low': round(nose, 1)},
        'tail': {'y': round(ymin, 1), 'z_low': round(tail, 1)},
        'bogie_pivot_yz': [q['bogie']['pivot_y_mm'], q['bogie']['pivot_z_mm']],
    }


def main():
    out = ROOT/'cad-output/side_profile.json'
    data = build()
    out.write_text(json.dumps(data, indent=1), encoding='utf-8')
    lo = lambda k: min(z for _, z in data[k]) if data[k] else None
    print(f"{out.relative_to(ROOT)}: sprung min Z {lo('sprung_bottom')}, bogie min Z {lo('bogie_bottom')}, rear min Z {lo('rear_bottom')}, "
          f"extent Y {data['extent_y']}, nose {data['nose']}, tail {data['tail']}")


if __name__ == '__main__':
    main()
