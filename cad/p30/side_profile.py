"""Side-view (Y-Z) underside and nose/tail silhouettes of the P30 (Eco) model for the 2-D drive simulation.

Terrain in the drive tests is uniform across X (full-width slope, step, bump), so the lowest point of the
robot at each Y station, taken over the whole width, is what can touch it. Each solid's bounding box is used
(conservative for rotated parts). Three sets are written:
  sprung    : frame, plates, electronics, sensors and the chassis-fixed part of the drive (holders, shafts)
  unsprung  : the parts that slide with the wheel (axle plate, bush housings, seats ...), relative to the axle
  casters   : caster forks/plates are left out; the caster wheels are modelled as circles by the simulation
python -m cad.p30.side_profile  ->  cad-output/p30/side_profile.json
"""
import json
import re
from pathlib import Path

from .build import P30, build_records

ROOT = Path(__file__).resolve().parents[2]
STEP = 10.0                      # mm, Y station spacing


def _moves_with_wheel(name):
    """Same rule as the web viewer: drive parts 30-46 (wheel, axle plate, housings, seats, stoppers) slide."""
    m = re.match(r'^(\d+)_', name)
    return bool(m) and 30 <= int(m.group(1)) <= 46


def silhouette(boxes, y0, y1):
    """boxes: [(ymin, ymax, zmin, zmax)] -> [[y, zmin]] at STEP stations (only stations covered by a box)."""
    out = []
    n = int(round((y1-y0)/STEP))
    for i in range(n+1):
        y = y0+i*STEP
        zs = [b[2] for b in boxes if b[0]-1e-6 <= y <= b[1]+1e-6]
        if zs:
            out.append([round(y, 1), round(min(zs), 2)])
    return out


def build(P=None):
    P = P or P30()
    records = build_records(P)
    sprung, unsprung = [], []
    ymin = ymax = 0.0
    zmax = 0.0
    for r in records:
        if r.group.startswith('caster_'):
            continue
        for s in r.shape.solids():
            bb = s.bounding_box()
            box = (bb.min.Y, bb.max.Y, bb.min.Z, bb.max.Z)
            if r.group in ('drive_left', 'drive_right') and _moves_with_wheel(r.name):
                if not r.name.startswith(('30_', '31_')):     # the tyre itself is the 90 mm circle
                    unsprung.append(box)
            else:
                sprung.append(box)
                ymin, ymax, zmax = min(ymin, bb.min.Y), max(ymax, bb.max.Y), max(zmax, bb.max.Z)
    axle_z = P.parts['drive_motor']['tire_dia']/2
    un = silhouette(unsprung, -300, 300)
    # nose/tail: lowest Z of anything that reaches within 15 mm of the front/rear extreme
    nose = min(b[2] for b in sprung if b[1] >= ymax-15)
    tail = min(b[2] for b in sprung if b[0] <= ymin+15)
    return {
        'revision': P.L['revision'],
        'note': 'Generated by python -m cad.p30.side_profile from the build123d records (solid bounding boxes, min Z over the full width). '
                'Unsprung Z values are relative to the ground at nominal ride height; the simulation moves them with the wheel slide.',
        'station_mm': STEP,
        'sprung_bottom': silhouette(sprung, round(ymin/STEP)*STEP, round(ymax/STEP)*STEP),
        'unsprung_bottom': un,
        'axle_z_nominal': axle_z,
        'extent_y': [round(ymin, 1), round(ymax, 1)],
        'top_z': round(zmax, 1),
        'nose': {'y': round(ymax, 1), 'z_low': round(nose, 1)},
        'tail': {'y': round(ymin, 1), 'z_low': round(tail, 1)},
    }


def main():
    out = ROOT/'cad-output/p30/side_profile.json'
    data = build()
    out.write_text(json.dumps(data, indent=1), encoding='utf-8')
    lo = min(z for _, z in data['sprung_bottom'])
    ul = min(z for _, z in data['unsprung_bottom']) if data['unsprung_bottom'] else None
    print(f"{out.relative_to(ROOT)}: sprung {len(data['sprung_bottom'])} stations (min Z {lo}), unsprung min Z {ul}, "
          f"extent Y {data['extent_y']}, nose {data['nose']}, tail {data['tail']}")


if __name__ == '__main__':
    main()
